    @GetMapping("/status/{status}")
    @PreAuthorize("hasAnyRole('ADMIN','PROCUREMENT','FINANCE','MANAGER')")
    public ResponseEntity<ApiResponse<List<PurchaseOrderResponseDTO>>> getByStatus(@PathVariable PurchaseOrderStatus status) {

        return ResponseEntity.ok(new ApiResponse<>(purchaseOrderService.getPurchaseOrdersByStatus(status)));
    }

    // Get Orders of Supplier

    @GetMapping("/supplier/{supplierId}")
    @PreAuthorize("hasAnyRole('ADMIN','PROCUREMENT','FINANCE')")
    public ResponseEntity<ApiResponse<List<PurchaseOrderResponseDTO>>> getSupplierOrders(@PathVariable Long supplierId) {

        return ResponseEntity.ok(new ApiResponse<>(purchaseOrderService.getSupplierOrders(supplierId)));
    }

    // Orders Generated By Logged Procurement Officer

    @GetMapping("/my-orders")
    @PreAuthorize("hasRole('PROCUREMENT')")
    public ResponseEntity<ApiResponse<List<PurchaseOrderResponseDTO>>> myOrders() {

        return ResponseEntity.ok(new ApiResponse<>(purchaseOrderService.getGeneratedOrders(currentUser.get().getId())));
    }

