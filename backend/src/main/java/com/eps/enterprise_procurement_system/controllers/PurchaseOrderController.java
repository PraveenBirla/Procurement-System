    // Export All Purchase Orders Excel

    @GetMapping("/export")
    @PreAuthorize("hasAnyRole('ADMIN','PROCUREMENT','FINANCE')")
    public ResponseEntity<byte[]> exportPurchaseOrders() {

        byte[] excel = purchaseOrderService.exportPurchaseOrders();

        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION,
                        "attachment; filename=PurchaseOrders.xlsx")
                .contentType(MediaType.APPLICATION_OCTET_STREAM)
                .body(excel);
    }

    // Export Purchase Orders By Status

    @GetMapping("/export/status/{status}")
    @PreAuthorize("hasAnyRole('ADMIN','PROCUREMENT','FINANCE')")
    public ResponseEntity<byte[]> exportByStatus(
            @PathVariable PurchaseOrderStatus status) {

        byte[] excel =
                purchaseOrderService.exportPurchaseOrdersByStatus(status);

        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION,
                        "attachment; filename=PurchaseOrders_" + status + ".xlsx")
                .contentType(MediaType.APPLICATION_OCTET_STREAM)
                .body(excel);
    }

    // Export Supplier Purchase Orders

    @GetMapping("/export/supplier/{supplierId}")
    @PreAuthorize("hasAnyRole('ADMIN','PROCUREMENT','FINANCE')")
    public ResponseEntity<byte[]> exportSupplierOrders(@PathVariable Long supplierId) {

        byte[] excel = purchaseOrderService.exportSupplierOrders(supplierId);

        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION,
                        "attachment; filename=SupplierOrders.xlsx")
                .contentType(MediaType.APPLICATION_OCTET_STREAM)
                .body(excel);
    }

